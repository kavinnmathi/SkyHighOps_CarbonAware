"""Dataset loading, preprocessing, synthetic sample generation and the optional
UK Carbon Intensity API downloader.

DATA ORIGIN LABELS used throughout the project
  REAL_OBSERVATION  - values read from a real public dataset file
  SYNTHETIC_SAMPLE  - generated by this project's seeded generator (NOT real data)
  SIMULATED_ASSUMPTION - attributes the real data does not contain (e.g. latency)
"""
from __future__ import annotations

import json
import time
import urllib.error
import urllib.request
from datetime import datetime, timedelta, timezone

import numpy as np
import pandas as pd

from .config import resolve_path
from .errors import DataError
from .models import JobSpec

CARBON_API_BASE = "https://api.carbonintensity.org.uk"
STEPS_PER_DAY = 48  # the National Grid series has 30-minute resolution


# ---------------------------------------------------------------- carbon data
def load_carbon_csv(path, expected_step_minutes: int = 30) -> pd.DataFrame:
    """Load a carbon-intensity CSV with columns 'from' and 'actual' and/or 'forecast'.

    Returns a DataFrame indexed by UTC timestamp with columns:
      ci (gCO2/kWh, uses 'actual', falls back to 'forecast'), minutes_of_day, dow
    Attributes: df.attrs['n_filled'] number of interpolated gaps.
    """
    p = resolve_path(path)
    if not p.exists():
        raise DataError(f"Carbon-intensity file not found: {p}. "
                        "Run with the default sample mode, or see README (optional real data).")
    try:
        raw = pd.read_csv(p)
    except Exception as exc:  # pandas raises many error types
        raise DataError(f"Could not read {p}: {exc}") from exc
    if "from" not in raw.columns or not ({"actual", "forecast"} & set(raw.columns)):
        raise DataError(f"{p.name} needs a 'from' column and an 'actual' and/or 'forecast' column.")
    raw["from"] = pd.to_datetime(raw["from"], utc=True, errors="coerce")
    raw = raw.dropna(subset=["from"]).drop_duplicates("from").sort_values("from")
    ci = pd.to_numeric(raw["actual"], errors="coerce") if "actual" in raw.columns else pd.Series(np.nan, index=raw.index)
    if "forecast" in raw.columns:
        ci = ci.fillna(pd.to_numeric(raw["forecast"], errors="coerce"))
    s = pd.Series(ci.values, index=pd.DatetimeIndex(raw["from"].values, tz="UTC"), name="ci")
    full_index = pd.date_range(s.index.min(), s.index.max(), freq=f"{expected_step_minutes}min")
    s = s.reindex(full_index)
    n_missing = int(s.isna().sum())
    s = s.interpolate(limit=6, limit_direction="both")
    if s.isna().any():
        raise DataError(f"{p.name} has gaps longer than 6 steps; re-download or choose another period.")
    if (s < 0).any():
        raise DataError(f"{p.name} contains negative carbon intensity values.")
    out = pd.DataFrame({"ci": s.astype(float)})
    out["minutes_of_day"] = out.index.hour * 60 + out.index.minute
    out["dow"] = out.index.dayofweek
    out.attrs["n_filled"] = n_missing
    origins = raw["data_origin"].dropna().unique() if "data_origin" in raw.columns else []
    out.attrs["origin"] = str(origins[0]) if len(origins) == 1 else (
        "MIXED_OR_UNKNOWN_ORIGIN" if len(origins) else "UNKNOWN_ORIGIN")
    return out


def generate_synthetic_carbon(days: int = 37, seed: int = 7) -> pd.DataFrame:
    """SYNTHETIC grid carbon intensity (daily + weekly pattern + slow AR(1) noise).

    This is NOT real data. It only exists so the project runs offline.
    """
    rng = np.random.default_rng(seed)
    n = days * STEPS_PER_DAY
    idx = pd.date_range("2024-01-01 00:00", periods=n, freq="30min", tz="UTC")  # a Monday
    tod = (idx.hour * 60 + idx.minute) / 1440.0
    daily = 45 * np.sin(2 * np.pi * (tod - 0.45))          # peak around early evening
    weekend = np.where(idx.dayofweek >= 5, -20.0, 0.0)
    noise = np.zeros(n)
    for i in range(1, n):                                   # slow "wind" component
        noise[i] = 0.985 * noise[i - 1] + rng.normal(0, 4.0)
    actual = np.clip(160 + daily + weekend + noise + rng.normal(0, 3, n), 30, 380)
    return pd.DataFrame({
        "from": idx.strftime("%Y-%m-%dT%H:%MZ"),
        "actual": np.round(actual, 1),
        "data_origin": "SYNTHETIC_SAMPLE",
    })


def download_carbon_intensity(start: str, end: str, out_path, retries: int = 3) -> int:
    """Download half-hourly GB carbon intensity from the public UK Carbon Intensity API.

    No API key is needed. The API limits each request to 14 days, so the range is
    split into 13-day chunks. Dates are 'YYYY-MM-DD' (UTC). Returns rows saved.
    """
    try:
        t0 = datetime.strptime(start, "%Y-%m-%d").replace(tzinfo=timezone.utc)
        t1 = datetime.strptime(end, "%Y-%m-%d").replace(tzinfo=timezone.utc)
    except ValueError as exc:
        raise DataError("Dates must look like 2025-01-31 (YYYY-MM-DD).") from exc
    if t1 <= t0:
        raise DataError("--end must be after --start.")
    rows, cur = [], t0
    while cur < t1:
        nxt = min(cur + timedelta(days=13), t1)
        url = f"{CARBON_API_BASE}/intensity/{cur:%Y-%m-%dT%H:%MZ}/{nxt:%Y-%m-%dT%H:%MZ}"
        payload = None
        for attempt in range(1, retries + 1):
            try:
                req = urllib.request.Request(url, headers={"Accept": "application/json"})
                with urllib.request.urlopen(req, timeout=30) as resp:
                    payload = json.loads(resp.read().decode("utf-8"))
                break
            except (urllib.error.URLError, TimeoutError, json.JSONDecodeError) as exc:
                if attempt == retries:
                    raise DataError(f"Download failed for {url}: {exc}. "
                                    "Check your internet connection and try again.") from exc
                time.sleep(2 * attempt)
        for rec in payload.get("data", []):
            inten = rec.get("intensity", {})
            rows.append({"from": rec.get("from"), "to": rec.get("to"),
                         "forecast": inten.get("forecast"), "actual": inten.get("actual"),
                         "index": inten.get("index"), "data_origin": "REAL_OBSERVATION"})
        cur = nxt
    if not rows:
        raise DataError("The API returned no data for that period.")
    df = pd.DataFrame(rows).drop_duplicates("from").sort_values("from")
    p = resolve_path(out_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(p, index=False)
    return len(df)


# ------------------------------------------------------------------ workloads
def generate_synthetic_workload(sim_steps: int, wcfg: dict, seed: int = 42) -> pd.DataFrame:
    """SYNTHETIC jobs with CPU, memory and latency requirements (not real trace data)."""
    rng = np.random.default_rng(seed)
    rows, job_id = [], 0
    for t in range(sim_steps):
        tod = (t % STEPS_PER_DAY) / STEPS_PER_DAY
        rate = wcfg["jobs_per_step"] * (1 + 0.5 * np.sin(2 * np.pi * (tod - 0.3)))
        for _ in range(rng.poisson(max(rate, 0.0))):
            sensitive = rng.random() < wcfg["latency_sensitive_fraction"]
            cpu = float(rng.choice([0.5, 1, 2, 4] if sensitive else [0.5, 1, 2, 4, 8],
                                   p=[0.2, 0.35, 0.3, 0.15] if sensitive else [0.15, 0.3, 0.3, 0.15, 0.1]))
            dur = int(np.clip(round(rng.lognormal(np.log(3), 0.8)), 1, wcfg["max_duration_steps"]))
            rows.append({
                "job_id": job_id, "arrival_step": t, "duration_steps": dur,
                "cpu_req": cpu, "mem_req_gb": cpu * float(rng.choice([1, 2, 4])),
                "cpu_util": round(float(rng.uniform(0.3, 1.0)), 3),
                "latency_req_ms": float(rng.choice(wcfg["latency_sensitive_req_ms"])) if sensitive
                else float(wcfg["latency_tolerant_req_ms"]),
                "slack_steps": 0 if sensitive else int(rng.choice(wcfg["slack_choices_steps"])),
                "data_mb": round(float(rng.lognormal(np.log(300), 0.8)), 1),
                "data_origin": "SYNTHETIC_SAMPLE",
            })
            job_id += 1
    return pd.DataFrame(rows)


_WORKLOAD_COLS = ["job_id", "arrival_step", "duration_steps", "cpu_req", "mem_req_gb",
                  "cpu_util", "latency_req_ms", "slack_steps", "data_mb"]


def workload_from_dataframe(df: pd.DataFrame) -> list[JobSpec]:
    missing = [c for c in _WORKLOAD_COLS if c not in df.columns]
    if missing:
        raise DataError(f"Workload table is missing columns: {missing}")
    jobs = []
    for r in df.itertuples(index=False):
        jobs.append(JobSpec(int(r.job_id), int(r.arrival_step), max(1, int(r.duration_steps)),
                            float(r.cpu_req), float(r.mem_req_gb), float(r.cpu_util),
                            float(r.latency_req_ms), int(r.slack_steps), float(r.data_mb)))
    return jobs


