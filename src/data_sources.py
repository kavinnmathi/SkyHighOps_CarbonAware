def load_google_trace_extract(path, cfg: dict, sim_steps: int, seed: int = 42) -> pd.DataFrame:
    """Convert a user-made extract of the Google 2019 Borg trace into scheduler jobs.

    Required CSV columns (produced by docs/google_trace_bigquery.sql):
      collection_id, instance_index, start_time, end_time (microseconds, as in the trace),
      avg_cpus, avg_memory (normalised units, as in the trace).
    REAL: arrival time, duration, average CPU and memory usage.
    SIMULATED_ASSUMPTION: scale to cores/GB, cpu_util, latency requirement, slack, data size.
    """
    p = resolve_path(path)
    if not p.exists():
        raise DataError(f"Google trace extract not found: {p}. See docs/DATASETS.md.")
    raw = pd.read_csv(p)
    need = ["collection_id", "instance_index", "start_time", "end_time", "avg_cpus", "avg_memory"]
    if [c for c in need if c not in raw.columns]:
        raise DataError(f"Extract must contain columns {need}.")
    m = cfg["google_trace_mapping"]
    step_s = cfg["time_step_minutes"] * 60
    raw = raw.apply(pd.to_numeric, errors="coerce").dropna(subset=need)
    raw = raw[(raw.end_time > raw.start_time) & (raw.start_time > 0) & (raw.end_time < 1e15)]
    if raw.empty:
        raise DataError("No valid rows left after cleaning the Google trace extract.")
    t0 = raw.start_time.min()
    raw = raw.assign(arrival_step=((raw.start_time - t0) / 1e6 // step_s).astype(int),
                     dur_s=(raw.end_time - raw.start_time) / 1e6)
    raw = raw[raw.arrival_step < sim_steps]
    if len(raw) > m["max_jobs"]:
        raw = raw.sample(m["max_jobs"], random_state=seed)
    raw = raw.sort_values("arrival_step").reset_index(drop=True)
    if raw.empty:
        raise DataError("The extract has no jobs inside the simulation window.")
    rng = np.random.default_rng(seed)
    n = len(raw)
    sensitive = rng.random(n) < 0.4
    out = pd.DataFrame({
        "job_id": np.arange(n),
        "arrival_step": raw.arrival_step,
        "duration_steps": np.clip(np.ceil(raw.dur_s / step_s), 1, 24).astype(int),
        "cpu_req": np.clip(raw.avg_cpus * m["cpu_scale_cores"], 0.25, m["max_cpu_per_job"]).round(3),
        "mem_req_gb": np.clip(raw.avg_memory * m["mem_scale_gb"], 0.25, m["max_mem_per_job_gb"]).round(3),
        "cpu_util": rng.uniform(0.5, 1.0, n).round(3),
        "latency_req_ms": np.where(sensitive, rng.choice([15, 25, 50], n), 200).astype(float),
        "slack_steps": np.where(sensitive, 0, rng.choice([0, 12, 24, 48], n)),
        "data_mb": rng.lognormal(np.log(300), 0.8, n).round(1),
        "data_origin": "REAL_TRACE_FIELDS+SIMULATED_ASSUMPTIONS",
    })
    return out
